// OpenAPI → TS codegen (PLAN Phase 0 item 6).
// Generates typed paths/components from the vendored OFAPI spec — the field-level
// source of truth (CLAUDE.md). Output is committed so builds never depend on codegen.
// Usage: pnpm codegen:ofapi
import openapiTS, { astToString } from 'openapi-typescript';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const specPath = join(root, 'docs/vendor/onlyfansapi/openapi.json');
const outPath = join(root, 'apps/desktop/src/main/ofapi/ofapi.gen.ts');

const spec = JSON.parse(readFileSync(specPath, 'utf8'));
const ast = await openapiTS(spec, {
  exportType: true,
});
const header = `// GENERATED by scripts/codegen-ofapi.mjs from docs/vendor/onlyfansapi/openapi.json — do not edit.\n// Regenerate: pnpm codegen:ofapi\n/* eslint-disable */\n`;
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, header + astToString(ast));
console.log(`wrote ${outPath}`);
